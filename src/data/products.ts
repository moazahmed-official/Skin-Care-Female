export const productBySlug = new Map(products.map((p) => [p.slug, p]));

export function productsByCategory(slug: string) {
  return products.filter((p) => p.category === slug);
}

export function relatedProducts(product: Product, limit = 3) {
  const picked = product.pairsWith
    .map((s) => productBySlug.get(s))
    .filter((p): p is Product => Boolean(p));
  if (picked.length >= limit) return picked.slice(0, limit);
  const filler = products.filter(
    (p) => p.slug !== product.slug && !picked.includes(p) && p.category === product.category,
  );
  return [...picked, ...filler].slice(0, limit);
}
